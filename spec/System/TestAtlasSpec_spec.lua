describe("AtlasSpec", function()
	local spec, nodes
	before_each(function()
		spec = new("AtlasSpec"):AtlasSpec("3_30")
		nodes = spec.tree.nodes
	end)

	it("paths, allocates and deallocates", function()
		assert.are.equal(0, spec:CountAllocNodes())
		assert.is_not_nil(spec.allocNodes[29045])
		local path = spec:GetPathToNode(nodes[63753])
		assert.are.equal(12, #path)
		assert.are.equal(nodes[63753], path[#path])
		spec:AllocNode(nodes[63753])
		assert.are.equal(12, spec:CountAllocNodes())
		assert.are.equal(0, #spec:GetPathToNode(nodes[63753]))
		assert.are.equal(0, #spec:GetPathToNode(spec.tree.masteries[1]))
		spec:DeallocNode(nodes[57123])
		assert.is_nil(spec.allocNodes[63753])
		assert.are.equal(10, spec:CountAllocNodes())
	end)

	it("handles variants and gateways", function()
		spec:AllocNode(nodes[45404])
		assert.is_true(spec:SetVariant(45404, 55878))
		assert.is_false(spec:SetVariant(45404, 1))
		assert.are.equal(55878, spec.variantSelections[45404])
		spec:DeallocNode(nodes[45404])
		assert.is_nil(spec.variantSelections[45404])
		spec:AllocNode(nodes[17000])
		assert.are.equal(1, #spec:GetPathToNode(nodes[13842]))
	end)

	it("round-trips xml, versions and undo", function()
		spec.title = "Breach"
		spec:AllocNode(nodes[45404])
		spec:SetVariant(45404, 5301)
		local xml = { elem = "Spec" }
		spec:Save(xml)
		local loaded = new("AtlasSpec"):AtlasSpec("3_30")
		loaded:Load(xml)
		assert.are.same(spec:GetAllocatedIds(), loaded:GetAllocatedIds())
		assert.are.equal(5301, loaded.variantSelections[45404])
		assert.are.equal("Breach", loaded.title)
		local unknown = new("AtlasSpec"):AtlasSpec("3_30")
		unknown:Load({ elem = "Spec", attrib = { treeVersion = "9_99", nodes = "57123" } })
		assert.are.equal(latestAtlasTreeVersion, unknown.treeVersion)
		spec:AddUndoState()
		spec:ResetNodes()
		spec:AddUndoState()
		spec:Undo()
		assert.are.equal(13, spec:CountAllocNodes())
		local dropped = spec:SetTreeVersion("3_18")
		assert.are.equal("3_18", spec.treeVersion)
		assert.is_true(dropped >= 0)
	end)
end)
