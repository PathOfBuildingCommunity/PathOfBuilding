describe("AtlasTree", function()
	it("loads the latest atlas tree", function()
		local tree = main:LoadAtlasTree("3_30")
		assert.are.equal(150, tree.totalPoints)
		assert.are.equal("Keystone", tree.nodes[63753].type)
		assert.are.equal("Thorough Exploration", tree.nodes[63753].dn)
		assert.is_true(math.abs(tree.nodes[57123].x + 6580.03) < 0.5)
		assert.is_true(math.abs(tree.nodes[57123].y + 6724.81) < 0.5)
		assert.are.equal("Root", tree.nodes[29045].type)
		assert.are.equal("Root", tree.nodes[0].type)
		assert.are.equal("Wormhole", tree.nodes[17000].type)
		assert.are.equal(2, #tree:GetWormholePartners(tree.nodes[17000]))
		assert.are.equal(2, #tree.nodes[45404].variants)
		assert.are.equal(55878, tree.nodes[45404].variants[1].effect)
		assert.is_true(#tree.masteries > 0)
		for _, connector in ipairs(tree.connectors) do
			assert.is_false(connector.node1.type == "Wormhole" and connector.node2.type == "Wormhole")
			assert.are_not.equal("Mastery", connector.node1.type)
			assert.are_not.equal("Mastery", connector.node2.type)
		end
		assert.are.equal(tree, main:LoadAtlasTree("9_99"))
	end)

	it("resolves stat markup", function()
		local resolve = common.classes.AtlasTree.ResolveMarkup
		assert.are.equal("3% increased Threads found", resolve("3% increased [Thread|Threads] found"))
		assert.are.equal("Breach", resolve("[Breach]"))
	end)

	it("loads every registered version", function()
		for _, version in ipairs(atlasTreeVersions) do
			local tree = main:LoadAtlasTree(version.key)
			assert.is_true(tree.totalPoints > 0, version.key)
			assert.is_true(#tree.startNodes > 0, version.key)
			assert.is_not_nil(next(tree.spriteMap), version.key)
			assert.is_not_nil(tree.assets.PSSkillFrame, version.key)
			assert.is_not_nil(tree.assets.AtlasPassiveSkillScreenStart, version.key)
			local _, sample = next(tree.spriteMap)
			local _, sprite = next(sample)
			assert.is_not_nil(sprite.handle, version.key)
		end
		assert.are.equal(132, main:LoadAtlasTree("3_18").totalPoints)
	end)
end)
