if not loadStatFile then
	dofile("statdesc.lua")
end
loadStatFile("stat_descriptions.csd")

local out = io.open("../Data/Viscera.lua", "w")
out:write("-- This file is automatically generated, do not edit!\n")
out:write("-- Item data (c) Grinding Gear Games\n\nreturn {\n")
local baseTypes = dat("BaseItemTypes")
local prefixMap = {
	["viscera_low"] = "Lesser ",
	["viscera_high"] = "Greater ",
}
local visceraNum = 0
for mod in dat("Mods"):Rows() do
	if mod.Id:match("^VisceraMod") then
		visceraNum += 1
		local prefix = ""
		for _, tag in ipairs(mod.Tags) do
			if prefixMap[tag.Id] then
				prefix = prefixMap[tag.Id]
				break
			end
		end
		local numeral = mod.Id:match("(%d+)$")
		local baseType = baseTypes:GetRow("Id", "Metadata/Items/Viscera/Viscera" .. mod.Family[1].Id:gsub("^VisceraMod", ""):gsub("^Viscera", ""):gsub(" ", ""))
		if not baseType then
			error("Could not find base type for " .. "Metadata/Items/Viscera/Viscera" .. mod.Family[1].Id:gsub("^VisceraMod", ""):gsub("^Viscera", ""):gsub(" ", ""))
		end
		out:write("[[\n" .. (prefix or "") .. baseType.Name .. (numeral and " " .. numeral or ""))
		out:write("\n" .. baseType.Name)
		local stats, orders = describeMod(mod)
		out:write("\nImplicits: " .. #stats)
		for _, stat in ipairs(stats) do
			out:write("\n" .. stat)
		end
		out:write("\n]],\n")
	end
end
out:write("}\n")
out:close()
print("Wrote " .. visceraNum .. " viscera to ../Data/Viscera.lua")
