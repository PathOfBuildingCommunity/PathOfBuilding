local out = io.open("../Data/Misc.lua", "w")
out:write("-- This file is automatically generated, do not edit!\n\n")
out:write('---@class MiscDataExport\n')
out:write('local out = {}\n')
local evasion = ""
local accuracy = ""
local life = ""
local altLife1 = ""
local altLife2 = ""
local allyLife = ""
local allyDamage = ""
local damage = ""
local armour = ""
local ailmentThreshold = ""
local monsterPhysConversionMulti = ""
for stats in dat("DefaultMonsterStats"):Rows() do
	evasion = evasion .. stats.Evasion .. ", "
	accuracy = accuracy .. stats.Accuracy .. ", "
	life = life .. stats.MonsterLife .. ", "
	altLife1 = altLife1 .. stats.AltLife1 .. ", "
	altLife2 = altLife2 .. stats.AltLife2 .. ", "
	allyLife = allyLife .. stats.MinionLife .. ", "
	damage = damage .. stats.Damage .. ", "
	allyDamage = allyDamage .. stats.MinionDamage .. ", "
	--armour = armour .. stats.Armour .. ", " The table here is wrong so we generate it instead
	ailmentThreshold = ailmentThreshold .. stats.AilmentThreshold .. ", "
	monsterPhysConversionMulti = monsterPhysConversionMulti .. stats.MonsterPhysConversionMulti .. ", "
end
for i = 1, 100 do
	armour = armour .. math.floor((10 + 2 * i ) * ( ( 1 + dat("GameConstants"):GetRow("Id", "MonsterDamageReductionImprovement").Value / dat("GameConstants"):GetRow("Id", "MonsterDamageReductionImprovement").Divisor / 100 ) ^ i)) .. ", "
end
out:write('-- From DefaultMonsterStats.dat\n')
out:write('out.monsterEvasionTable = { ' .. evasion .. '}\n') --This table is off by about 0.5% in some cases but is quicker than generating the value at runtime
out:write('out.monsterAccuracyTable = { ' .. accuracy .. '}\n')
out:write('out.monsterLifeTable = { ' .. life .. '}\n')
out:write('out.monsterLifeTable2 = { ' .. altLife1 .. '}\n')
out:write('out.monsterLifeTable3 = { ' .. altLife2 .. '}\n')
out:write('out.monsterAllyLifeTable = { ' .. allyLife .. '}\n')
out:write('out.monsterDamageTable = { ' .. damage .. '}\n')
out:write('out.monsterAllyDamageTable = { ' .. allyDamage .. '}\n')
out:write('out.monsterArmourTable = { ' .. armour .. '}\n')
out:write('out.monsterAilmentThresholdTable = { ' .. ailmentThreshold .. '}\n')
out:write('out.monsterPhysConversionMultiTable = { ' .. monsterPhysConversionMulti .. '}\n')

out:write('-- From GameConstants.dat\n')
out:write('out.gameConstants = {\n')
for row in dat("GameConstants"):Rows() do
	out:write('\t["' .. row.Id .. '"] = ' .. row.Value / row.Divisor .. ',\n')
end
out:write('}\n')

out:write('-- From Metadata/Characters/Character.ot\n')
out:write('out.characterConstants = {\n')
local file = getFile("Metadata/Characters/Character.ot")
if not file then return nil end
local text = convertUTF16to8(file)
local inWantedBlock = false
for line in text:gmatch("[^\r\n]+") do
	-- Detect start of a block
	if line:match("^Stats") or line:match("^Pathfinding") then
		inWantedBlock = true
	elseif inWantedBlock and line:match("^}") then
		inWantedBlock = false
	elseif inWantedBlock and line:find("=") then
		local key, value = line:gsub("%s+",""):match("^(.-)=(.+)$")
		if key and value then
			out:write('\t["' .. key .. '"] = ' .. value .. ',\n')
		end
	end
end
out:write('}\n')

out:write('-- From Metadata/Monsters/Monster.ot\n')
out:write('out.monsterConstants = {\n')
local file = getFile("Metadata/Monsters/Monster.ot")
if not file then return nil end
local text = convertUTF16to8(file)
local inWantedBlock = false
for line in text:gmatch("[^\r\n]+") do
	-- Detect start of a block
	if line:match("^Stats") then
		inWantedBlock = true
	elseif inWantedBlock and line:match("^}") then
		inWantedBlock = false
	elseif inWantedBlock and line:find("=") then
		local key, value = line:gsub("%s+",""):match("^(.-)=(.+)$")
		if key and value then
			out:write('\t["' .. key .. '"] = ' .. value .. ',\n')
		end
	end
end
out:write('}\n')

local totemMult = ""
local keys = { }
for var in dat("SkillTotemVariations"):Rows() do
	if not keys[var.SkillTotem] then
		keys[var.SkillTotem] = true
		totemMult = totemMult .. "[" .. var.SkillTotem .. "] = " .. var.MonsterVariety.LifeMultiplier / 100 .. ", "
	end
end
out:write('-- From MonsterVarieties.dat combined with SkillTotemVariations.dat\n')
out:write('out.totemLifeMult = { ' .. totemMult .. '}\n')

out:write('out.monsterVarietyLifeMult = {\n')
local cachedEntry = { }
for row in dat("MonsterVarieties"):Rows() do
	for _, mod in ipairs(row.Mods) do
		if mod.Id == "MonsterNecromancerRaisable" and not cachedEntry['"' .. row.Name .. '"'] then
			out:write('\t["' .. row.Name .. '"] = ' .. row.LifeMultiplier/100 .. ',\n')
			cachedEntry['"' .. row.Name .. '"'] = true
			break
		end
	end
end
out:write('}\n')

out:write('-- From MonsterMapDifficulty.dat\n')
out:write('out.mapLevelLifeMult = { ')
for row in dat("MonsterMapDifficulty"):Rows() do
	out:write('[' .. row.AreaLevel .. '] = ' .. (1+row.LifePercentIncrease/100) .. ', ')
end
out:write('}\n')

local mapBossLifeMult = ""
local mapBossAilmentMult = ""
for var in dat("MonsterMapBossDifficulty"):Rows() do
	mapBossLifeMult = mapBossLifeMult .. "[" .. var.AreaLevel .. "] = " .. 1 + var.BossLifePercentIncrease / 100 .. ", "
	mapBossAilmentMult = mapBossAilmentMult .. "[" .. var.AreaLevel .. "] = " .. (100 + var.BossAilmentPercentDecrease) / 100 .. ", "
end

out:write('-- From MonsterMapBossDifficulty.dat\n')
out:write('out.mapLevelBossLifeMult = { ' .. mapBossLifeMult .. '}\n')
out:write('out.mapLevelBossAilmentMult = { ' .. mapBossAilmentMult .. '}\n')

out:write('-- From VillageBalancePerLevelShared.dat\n')
out:write('out.goldRespecPrices = { ')
for row in dat("VillageBalancePerLevelShared"):Rows() do
	out:write(row.GoldRespec .. ', ')
end
out:write('}\n')

out:write('return out\n')
out:close()

print("Misc data exported.")
