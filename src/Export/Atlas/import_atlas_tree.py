#!/usr/bin/env python3
import argparse
import hashlib
import json
import os
import re
import sys
import urllib.error
import urllib.request

TAGS_URL = "https://api.github.com/repos/grindinggear/atlastree-export/tags?per_page=100"
RAW_URL = "https://raw.githubusercontent.com/grindinggear/atlastree-export/{tag}/{path}"
GENERATED_HEADER = "-- This file is automatically generated, do not edit!"
IMAGE_DIR = "Images"
IMAGE_MAP_RE = re.compile(r'\["([^"]+)"\] = "([^"]+)"')
TAG_RE = re.compile(r"^(\d+)\.(\d+)\.(\d+)((?:-ruthless)?)(?:-atlas)?$")
PREFERRED_ZOOM = "0.3835"


def tag_to_key(tag):
    match = TAG_RE.match(tag)
    if not match:
        return None
    major, minor, patch, ruthless = match.groups()
    key = f"{major}_{minor}" if patch == "0" else f"{major}_{minor}_{patch}"
    return key + ("_ruthless" if ruthless else "")


def tag_display(tag):
    major, minor, patch, ruthless = TAG_RE.match(tag).groups()
    return f"{major}.{minor}.{patch}" + (" (Ruthless)" if ruthless else "")


def tag_sort_key(tag):
    major, minor, patch, ruthless = TAG_RE.match(tag).groups()
    return (int(major), int(minor), int(patch), 1 if ruthless else 0)


def select_tags(tags):
    chosen = {}
    for tag in tags:
        key = tag_to_key(tag)
        if key is None:
            continue
        current = chosen.get(key)
        if current is None or (tag.endswith("-atlas") and not current.endswith("-atlas")):
            chosen[key] = tag
    return sorted(chosen.values(), key=tag_sort_key)


def lua_string(value):
    out = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
    return f'"{out}"'


def lua_number(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    text = repr(value)
    return text[:-2] if text.endswith(".0") else text


def to_lua(value, indent=0):
    pad = "\t" * (indent + 1)
    end = "\t" * indent
    if value is None:
        return "nil"
    if isinstance(value, bool) or isinstance(value, (int, float)):
        return lua_number(value)
    if isinstance(value, str):
        return lua_string(value)
    if isinstance(value, list):
        items = [to_lua(item, indent + 1) for item in value if item is not None]
        if not items:
            return "{}"
        if all(not isinstance(item, (dict, list)) for item in value):
            return "{" + ",".join(items) + "}"
        return "{\n" + ",\n".join(pad + item for item in items) + "\n" + end + "}"
    if isinstance(value, dict):
        items = [f"{pad}[{lua_string(str(k))}]={to_lua(v, indent + 1)}" for k, v in value.items() if v is not None]
        if not items:
            return "{}"
        return "{\n" + ",\n".join(items) + "\n" + end + "}"
    raise TypeError(f"Unsupported type {type(value)}")


def strip_url(url):
    return url.split("?", 1)[0].rsplit("/", 1)[-1]


def pick_zoom(zooms):
    if PREFERRED_ZOOM in zooms:
        return zooms[PREFERRED_ZOOM]
    return zooms[max(zooms, key=float)]


def sprite_files(data):
    files = {}
    if "sprites" in data:
        for zooms in data["sprites"].values():
            sheet = pick_zoom(zooms)
            files[strip_url(sheet["filename"])] = sheet["filename"]
    for sheets in data.get("skillSprites", {}).values():
        sheet = sheets[-1]
        files[strip_url(sheet["filename"])] = sheet["filename"]
    for name, zooms in data.get("assets", {}).items():
        files[f"{name}.png"] = pick_zoom(zooms)
    return files


def http_get(url):
    headers = {"User-Agent": "atlas-tree-import"}
    token = os.environ.get("GITHUB_TOKEN")
    if token and "github" in url:
        headers["Authorization"] = f"Bearer {token}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as response:
        return response.read()


def write_if_changed(path, content):
    if os.path.exists(path):
        with open(path, "rb") as existing:
            if existing.read() == content:
                return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as target:
        target.write(content)
    return True


def fetch_asset(tag, basename, fallback_url):
    for url in (RAW_URL.format(tag=tag, path=f"assets/{basename}"), fallback_url):
        try:
            return http_get(url)
        except urllib.error.HTTPError:
            continue
    return None


def shared_image_name(basename, content):
    stem, ext = os.path.splitext(basename)
    return f"{stem}-{hashlib.sha1(content).hexdigest()[:10]}{ext}"


def read_image_map(path):
    if not os.path.exists(path):
        return {}
    with open(path, encoding="utf-8") as source:
        return dict(IMAGE_MAP_RE.findall(source.read()))


def write_image_map(path, image_map):
    lines = ["return {"]
    for basename in sorted(image_map):
        lines.append(f'\t["{basename}"] = "{image_map[basename]}",')
    lines.append("}")
    return write_if_changed(path, ("\n".join(lines) + "\n").encode("utf-8"))


def import_tag(tag, out_dir):
    key = tag_to_key(tag)
    atlas_dir = os.path.join(out_dir, "TreeData", "Atlas")
    target = os.path.join(atlas_dir, key)
    shared = os.path.join(atlas_dir, IMAGE_DIR)
    data = json.loads(http_get(RAW_URL.format(tag=tag, path="data.json")))
    changed = write_if_changed(os.path.join(target, "tree.lua"), ("return " + to_lua(data) + "\n").encode("utf-8"))
    map_path = os.path.join(target, "images.lua")
    known = read_image_map(map_path)
    image_map = {}
    missing = []
    for basename, url in sprite_files(data).items():
        mapped = known.get(basename)
        if mapped and os.path.exists(os.path.join(shared, mapped)):
            image_map[basename] = mapped
            continue
        legacy = os.path.join(target, basename)
        if os.path.exists(legacy):
            with open(legacy, "rb") as source:
                content = source.read()
        else:
            content = fetch_asset(tag, basename, url)
        if content is None:
            missing.append(basename)
            continue
        mapped = shared_image_name(basename, content)
        changed = write_if_changed(os.path.join(shared, mapped), content) or changed
        image_map[basename] = mapped
        if os.path.exists(legacy):
            os.remove(legacy)
            changed = True
    changed = write_image_map(map_path, image_map) or changed
    schema = "sprites" if "sprites" in data else "skillSprites"
    print(f"{tag} -> {key} ({schema}){' updated' if changed else ''}")
    for basename in missing:
        print(f"  missing asset: {basename}")
    return key


def remove_unused_images(out_dir):
    atlas_dir = os.path.join(out_dir, "TreeData", "Atlas")
    shared = os.path.join(atlas_dir, IMAGE_DIR)
    if not os.path.isdir(shared):
        return
    used = set()
    for entry in os.listdir(atlas_dir):
        used.update(read_image_map(os.path.join(atlas_dir, entry, "images.lua")).values())
    for name in os.listdir(shared):
        if name not in used:
            os.remove(os.path.join(shared, name))
            print(f"removed unused image {name}")


def write_versions(tags, out_dir):
    lines = [GENERATED_HEADER, "", "return {"]
    for tag in tags:
        ruthless = "true" if "ruthless" in tag else "false"
        lines.append(f'\t{{ key = "{tag_to_key(tag)}", display = "{tag_display(tag)}", tag = "{tag}", ruthless = {ruthless} }},')
    lines.append("}")
    path = os.path.join(out_dir, "Data", "AtlasTreeVersions.lua")
    write_if_changed(path, ("\n".join(lines) + "\n").encode("utf-8"))


def existing_tags(out_dir):
    path = os.path.join(out_dir, "Data", "AtlasTreeVersions.lua")
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as versions:
        return re.findall(r'tag = "([^"]+)"', versions.read())


def main(argv=None):
    parser = argparse.ArgumentParser(description="Import atlas passive trees from the official atlas tree export")
    parser.add_argument("--tag", action="append", help="import only this tag (repeatable)")
    parser.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."), help="PoB src directory")
    args = parser.parse_args(argv)
    out_dir = os.path.abspath(args.out)
    if args.tag:
        bad = [tag for tag in args.tag if tag_to_key(tag) is None]
        if bad:
            sys.exit(f"Unsupported tag(s): {', '.join(bad)}")
        tags = select_tags(args.tag)
        known = existing_tags(out_dir)
        all_tags = select_tags(known + tags)
    else:
        remote = [entry["name"] for entry in json.loads(http_get(TAGS_URL))]
        tags = select_tags(remote)
        all_tags = tags
    for tag in tags:
        import_tag(tag, out_dir)
    if not args.tag:
        remove_unused_images(out_dir)
    write_versions(all_tags, out_dir)
    print(f"{len(all_tags)} atlas tree versions registered")


if __name__ == "__main__":
    main()
